const root = document.documentElement;
let lang = "en";
let roleTimer = null;

/* ---------- LANGUAGE ---------- */
function setLang(l) {
  lang = l;
  root.lang = l === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = I18N[l][el.dataset.i18n];
    if (v !== undefined) el.innerHTML = v;
  });
  document.title = I18N[l].title;
  document.getElementById("langBtn").textContent = l === "zh" ? "EN" : "中文";
  startTyping();
  try { localStorage.setItem("lang", l); } catch (e) {}
}
document.getElementById("langBtn").addEventListener("click", () => setLang(lang === "en" ? "zh" : "en"));

/* ---------- THEME ---------- */
function setTheme(t) {
  root.dataset.theme = t;
  document.getElementById("themeBtn").textContent = t === "dark" ? "☀" : "☾";
  try { localStorage.setItem("theme", t); } catch (e) {}
}
document.getElementById("themeBtn").addEventListener("click", () => setTheme(root.dataset.theme === "dark" ? "light" : "dark"));

/* ---------- TYPING EFFECT ---------- */
function startTyping() {
  clearTimeout(roleTimer);
  const el = document.getElementById("typed");
  const roles = I18N[lang].roles;
  let r = 0, c = 0, del = false;
  (function tick() {
    const word = roles[r];
    el.textContent = word.slice(0, c);
    if (!del && c === word.length) { del = true; roleTimer = setTimeout(tick, 1400); return; }
    if (del && c === 0) { del = false; r = (r + 1) % roles.length; }
    c += del ? -1 : 1;
    roleTimer = setTimeout(tick, del ? 40 : 90);
  })();
}

/* ---------- PARTICLE NETWORK BACKGROUND ---------- */
const canvas = document.getElementById("bg");
const ctx = canvas.getContext("2d");
let W, H, pts = [], mouse = { x: -999, y: -999 };
function resize() {
  W = canvas.width = innerWidth; H = canvas.height = innerHeight;
  pts = Array.from({ length: Math.min(110, Math.floor(W * H / 14000)) }, () => ({
    x: Math.random() * W, y: Math.random() * H,
    vx: (Math.random() - .5) * .5, vy: (Math.random() - .5) * .5
  }));
}
addEventListener("resize", resize);
addEventListener("mousemove", e => {
  mouse.x = e.clientX; mouse.y = e.clientY;
  const g = document.getElementById("glow");
  g.style.left = e.clientX + "px"; g.style.top = e.clientY + "px";
});
function draw() {
  const col = getComputedStyle(root).getPropertyValue("--accent").trim();
  ctx.clearRect(0, 0, W, H);
  for (const p of pts) {
    p.x += p.vx; p.y += p.vy;
    if (p.x < 0 || p.x > W) p.vx *= -1;
    if (p.y < 0 || p.y > H) p.vy *= -1;
    ctx.beginPath(); ctx.arc(p.x, p.y, 1.8, 0, 6.283); ctx.fillStyle = col; ctx.globalAlpha = .7; ctx.fill();
  }
  for (let i = 0; i < pts.length; i++) {
    for (let j = i + 1; j < pts.length; j++) {
      const d = Math.hypot(pts[i].x - pts[j].x, pts[i].y - pts[j].y);
      if (d < 130) {
        ctx.globalAlpha = (1 - d / 130) * .35; ctx.strokeStyle = col;
        ctx.beginPath(); ctx.moveTo(pts[i].x, pts[i].y); ctx.lineTo(pts[j].x, pts[j].y); ctx.stroke();
      }
    }
    const m = Math.hypot(pts[i].x - mouse.x, pts[i].y - mouse.y);
    if (m < 170) {
      ctx.globalAlpha = (1 - m / 170) * .7; ctx.strokeStyle = col;
      ctx.beginPath(); ctx.moveTo(pts[i].x, pts[i].y); ctx.lineTo(mouse.x, mouse.y); ctx.stroke();
    }
  }
  ctx.globalAlpha = 1;
  requestAnimationFrame(draw);
}

/* ---------- SCROLL REVEAL, BARS, COUNTERS ---------- */
const io = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (!e.isIntersecting) return;
    e.target.classList.add("show");
    e.target.querySelectorAll(".bar").forEach(b => b.classList.add("on"));
    e.target.querySelectorAll("[data-count]").forEach(n => {
      if (n.dataset.done) return; n.dataset.done = 1;
      const to = +n.dataset.count; let v = 0;
      const t = setInterval(() => { v++; n.textContent = v; if (v >= to) clearInterval(t); }, 300 / to + 120);
    });
    io.unobserve(e.target);
  });
}, { threshold: .15 });
document.querySelectorAll(".reveal").forEach(el => io.observe(el));
document.querySelectorAll(".bar i").forEach(i => i.style.setProperty("--w", i.dataset.level + "%"));

/* ---------- 3D TILT ---------- */
document.querySelectorAll(".tilt").forEach(el => {
  el.addEventListener("mousemove", e => {
    const r = el.getBoundingClientRect();
    const x = (e.clientX - r.left) / r.width - .5, y = (e.clientY - r.top) / r.height - .5;
    el.style.transform = `perspective(800px) rotateY(${x * 12}deg) rotateX(${-y * 12}deg) scale(1.02)`;
  });
  el.addEventListener("mouseleave", () => el.style.transform = "");
});

